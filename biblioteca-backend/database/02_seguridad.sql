-- ---------------------------------------------------------------------
-- USUARIOS: cuentas para iniciar sesión (admin y lectores)
-- La contraseña se guarda como hash BCrypt, nunca en texto plano.
-- ---------------------------------------------------------------------
create table if not exists usuarios (
    id             bigint generated by default as identity primary key,
    email          varchar(150) not null unique,
    password_hash  varchar(100) not null,
    rol            varchar(20)  not null check (rol in ('ADMIN', 'USUARIO')),
    socio_id       bigint unique references socios (id) on delete restrict,  -- null para el admin
    activo         boolean not null default true
);

-- ---------------------------------------------------------------------
-- Row Level Security (RLS)
-- Supabase publica automáticamente las tablas del esquema "public" en su
-- API REST. Sin RLS, cualquiera con la "anon key" del proyecto podría leer
-- o modificar los datos (¡incluidos los hashes de contraseñas!).
-- Activando RLS sin políticas, esa API queda bloqueada para estas tablas.
-- Spring Boot NO se ve afectado: se conecta como el dueño de las tablas.
-- ---------------------------------------------------------------------
alter table libros     enable row level security;
alter table ejemplares enable row level security;
alter table socios     enable row level security;
alter table prestamos  enable row level security;
alter table usuarios   enable row level security;
