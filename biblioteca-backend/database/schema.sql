insert into libros (titulo, autor, isbn, anio_publicacion) values
    ('Cien Años de Soledad', 'Gabriel García Márquez', '978-0307474728', 1967),
    ('Clean Code',           'Robert C. Martin',       '978-0132350884', 2008),
    ('El Quijote',           'Miguel de Cervantes',    '978-8424116286', 1605)
on conflict (isbn) do nothing;

insert into ejemplares (libro_id, codigo, estado, ubicacion)
select l.id, e.codigo, 'DISPONIBLE', e.ubicacion
from (values
    ('978-0307474728', 'CAS-001', 'Estante A1'),
    ('978-0307474728', 'CAS-002', 'Estante A1'),
    ('978-0132350884', 'CC-001',  'Estante B3'),
    ('978-8424116286', 'QUI-001', 'Estante A2')
) as e (isbn, codigo, ubicacion)
join libros l on l.isbn = e.isbn
on conflict (codigo) do nothing;

