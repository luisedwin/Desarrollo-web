-- ---------------------------------------------------------------------
-- LIBROS: el título como obra (un registro por título/ISBN)
-- ---------------------------------------------------------------------
create table if not exists libros (
    id                bigint generated by default as identity primary key,
    titulo            varchar(200) not null,
    autor             varchar(150),
    isbn              varchar(20),
    anio_publicacion  integer
);

-- Evita libros duplicados por ISBN (varios libros sin ISBN sí se permiten)
create unique index if not exists ux_libros_isbn on libros (isbn);

-- ---------------------------------------------------------------------
-- EJEMPLARES: cada copia física de un libro
-- ---------------------------------------------------------------------
create table if not exists ejemplares (
    id         bigint generated by default as identity primary key,
    libro_id   bigint not null references libros (id) on delete restrict,
    codigo     varchar(30) not null unique,      -- código de inventario / etiqueta
    estado     varchar(20) not null default 'DISPONIBLE'
               check (estado in ('DISPONIBLE', 'PRESTADO', 'MANTENIMIENTO', 'BAJA')),
    ubicacion  varchar(100)                       -- estante / sección
);

create index if not exists ix_ejemplares_libro on ejemplares (libro_id);

-- ---------------------------------------------------------------------
-- SOCIOS: personas registradas que pueden pedir préstamos
-- ---------------------------------------------------------------------
create table if not exists socios (
    id              bigint generated by default as identity primary key,
    nombre          varchar(100) not null,
    apellido        varchar(100) not null,
    documento       varchar(20)  not null unique,  -- DNI / cédula
    email           varchar(150) unique,
    telefono        varchar(20),
    fecha_registro  date    not null default current_date,
    activo          boolean not null default true
);

-- ---------------------------------------------------------------------
-- PRESTAMOS: qué socio se llevó qué ejemplar y cuándo lo devuelve
-- ---------------------------------------------------------------------
create table if not exists prestamos (
    id                         bigint generated by default as identity primary key,
    ejemplar_id                bigint not null references ejemplares (id) on delete restrict,
    socio_id                   bigint not null references socios (id) on delete restrict,
    fecha_prestamo             date not null default current_date,
    fecha_devolucion_prevista  date not null,
    fecha_devolucion_real      date,                -- null = todavía no lo devuelve
    estado                     varchar(20) not null default 'ACTIVO'
                               check (estado in ('ACTIVO', 'DEVUELTO', 'VENCIDO')),
    check (fecha_devolucion_prevista >= fecha_prestamo),
    check (fecha_devolucion_real is null or fecha_devolucion_real >= fecha_prestamo)
);

create index if not exists ix_prestamos_socio on prestamos (socio_id);

-- Un ejemplar solo puede tener UN préstamo sin devolver a la vez.
-- La BD lo garantiza aunque dos peticiones lleguen al mismo tiempo (validación concurrente).
create unique index if not exists ux_prestamos_ejemplar_activo
    on prestamos (ejemplar_id)
    where fecha_devolucion_real is null;

